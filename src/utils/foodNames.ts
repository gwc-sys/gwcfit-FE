const namesByKey = new Map(Object.entries(hindiNames).map(([name, hindi]) => [name.toLowerCase(), hindi]));

export function foodHindiName(name: string): string | undefined {
  return namesByKey.get(name.trim().toLowerCase());
}

export function foodDisplayName(name: string): string {
  const hindi = foodHindiName(name);
  return hindi ? `${name} (${hindi})` : name;
}
